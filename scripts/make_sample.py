"""Generate the open sample corpus in data/sample/.

The sample has two parts:

* One real object, the Mohenjo-daro "figure between two tigers" seal, whose
  photograph is public domain. Its signs are recorded as unreadable ("?") until
  they are transcribed from the CISI photograph and checked.
* A SYNTHETIC set of texts produced by a small Markov model. They only exist so
  the browser and statistics have something to run on. They are not Indus
  inscriptions and every row is flagged synthetic=True.

Run:  python scripts/make_sample.py
"""

from __future__ import annotations

import csv
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "sample"
SEED = 1977
SYNTH_SOURCE = "Synthetic, generated by scripts/make_sample.py (not real data)"

SITES = [
    ("MD", "Mohenjo-daro", "Pakistan", 27.329, 68.138),
    ("HR", "Harappa", "Pakistan", 30.631, 72.864),
    ("LO", "Lothal", "India", 22.522, 72.249),
    ("DH", "Dholavira", "India", 23.887, 70.213),
    ("KA", "Kalibangan", "India", 29.474, 74.130),
    ("CH", "Chanhu-daro", "Pakistan", 26.170, 68.320),
]

# Provisional working sign list: descriptive IDs only. Only the jar sign's
# Mahadevan number (M342) is filled in; other cross-references are left blank
# until checked against the published lists.
SIGNS = [
    ("JAR", "Jar", "vessel"),
    ("FISH", "Fish", "animal"),
    ("FISH_HAT", "Fish with roof mark", "animal"),
    ("FISH_DOTS", "Fish with internal dots", "animal"),
    ("MAN", "Standing man", "human"),
    ("MAN_POLE", "Man carrying pole", "human"),
    ("STROKE1", "One vertical stroke", "numeral"),
    ("STROKE2", "Two vertical strokes", "numeral"),
    ("STROKE3", "Three vertical strokes", "numeral"),
    ("STROKE4", "Four vertical strokes", "numeral"),
    ("COMB", "Comb-like sign", "object"),
    ("LOZENGE", "Lozenge", "geometric"),
    ("PLANT", "Branching plant", "plant"),
    ("POLE", "Vertical pole", "object"),
    ("OVAL_DOT", "Oval with inner mark", "geometric"),
    ("ARROW", "Arrow", "object"),
    ("WHEEL", "Wheel or circle with spokes", "geometric"),
    ("BOW", "Bow", "object"),
    ("CRAB", "Crab-like sign", "animal"),
    ("U_SIGN", "U-shaped sign", "geometric"),
    ("DOUBLE_U", "Doubled U", "geometric"),
    ("SPEAR", "Spear", "object"),
    ("TRIDENT", "Trident", "object"),
    ("BRACKETS", "Paired brackets", "geometric"),
    ("FORK", "Two-pronged fork", "object"),
    ("SQUARE_X", "Square with diagonals", "geometric"),
    ("BIRD", "Bird", "animal"),
    ("HOUSE", "Roofed enclosure", "object"),
]

ICONOGRAPHY = [
    "unicorn",
    "unicorn",
    "unicorn",
    "unicorn",
    "short-horned bull",
    "elephant",
    "rhinoceros",
    "zebu",
    "tiger",
    "",
]
OBJECT_TYPES = ["seal"] * 7 + ["sealing", "tablet", "pottery"]

INITIAL = ["FISH", "FISH_HAT", "MAN", "COMB", "LOZENGE", "WHEEL", "BOW", "SQUARE_X", "STROKE2"]
FINAL = ["JAR"] * 6 + ["STROKE1", "U_SIGN", "ARROW", "TRIDENT"]


def write(name: str, header: list[str], rows: list[list]) -> None:
    with open(OUT / f"{name}.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def synthetic_text(rng: random.Random, medial: list[str]) -> list[str]:
    length = rng.choices([1, 2, 3, 4, 5, 6, 7, 8], weights=[3, 8, 14, 20, 20, 15, 8, 4])[0]
    if length == 1:
        return [rng.choice(FINAL + INITIAL)]
    signs = [rng.choice(INITIAL)]
    prev = signs[0]
    while len(signs) < length - 1:
        # Numerals tend to precede fish signs; fish signs pair with each other.
        if prev.startswith("STROKE") and rng.random() < 0.6:
            nxt = rng.choice(["FISH", "FISH_HAT", "FISH_DOTS"])
        elif prev.startswith("FISH") and rng.random() < 0.3:
            nxt = rng.choice(["FISH", "FISH_DOTS", "STROKE3"])
        else:
            nxt = rng.choice(medial)
        signs.append(nxt)
        prev = nxt
    signs.append(rng.choice(FINAL))
    return signs


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    medial = [s[0] for s in SIGNS if s[0] != "JAR"]

    write(
        "sites",
        ["site_id", "name", "country", "lat", "lon", "source"],
        [[*s, "Approximate coordinates of the excavated site"] for s in SITES],
    )
    write(
        "signs",
        ["sign_id", "sign_list", "label", "graphic_class", "description", "source"],
        [[sid, "PROVISIONAL", label, cls, "", "Working list for the sample; not a published sign list"] for sid, label, cls in SIGNS],
    )
    write(
        "crosswalk",
        ["sign_id", "mahadevan", "parpola", "wells", "source"],
        [[sid, "342" if sid == "JAR" else "", "", "", "Mahadevan 1977" if sid == "JAR" else ""] for sid, _, _ in SIGNS],
    )

    obj_header = [
        "object_id", "site_id", "object_type", "material", "iconography", "period",
        "cisi_id", "mahadevan_id", "icit_id", "image_url", "image_licence", "synthetic", "source", "notes",
    ]
    text_header = [
        "text_id", "object_id", "side", "direction", "signs", "sign_list",
        "confidence", "synthetic", "source", "notes",
    ]
    objects = [[
        "MD-TIGER-1", "MD", "seal", "steatite", "figure between two rearing tigers", "Mature Harappan",
        "", "", "", "", "Public domain (Wikimedia Commons, uploaded by Ismoon)", "false",
        "Photograph on Wikimedia Commons; CISI and Mahadevan numbers to be confirmed",
        "Worked example. Catalogue numbers not yet verified against CISI.",
    ]]
    texts = [[
        "MD-TIGER-1-a", "MD-TIGER-1", "a", "rtl", " ".join(["?"] * 7), "PROVISIONAL", "unverified", "false",
        "Photograph on Wikimedia Commons",
        "About seven signs visible: lozenge at the right end, branching plant, vertical pole, "
        "oval with inner mark, a C-shaped sign, two strokes, comb-like sign at the left end. "
        "Description from the photograph only; transcribe from CISI before use.",
    ]]
    for i in range(1, 301):
        oid = f"SYN-{i:04d}"
        site = rng.choices([s[0] for s in SITES], weights=[40, 30, 10, 8, 7, 5])[0]
        otype = rng.choice(OBJECT_TYPES)
        icon = rng.choice(ICONOGRAPHY) if otype in ("seal", "sealing") else ""
        objects.append([oid, site, otype, "steatite" if otype == "seal" else "", icon, "",
                        "", "", "", "", "", "true", SYNTH_SOURCE, ""])
        texts.append([f"{oid}-a", oid, "a", "rtl", " ".join(synthetic_text(rng, medial)),
                      "PROVISIONAL", "certain", "true", SYNTH_SOURCE, ""])
    write("objects", obj_header, objects)
    write("texts", text_header, texts)
    print(f"Wrote {len(objects)} objects and {len(texts)} texts to {OUT}")


if __name__ == "__main__":
    main()
